/// Natural alignment for a DynValueType (mirrors `core::mem::align_of` for concrete types).
pub fn dyn_value_align(vt: &DynValueType) -> usize {
    match vt {
        DynValueType::U8 | DynValueType::I8 => 1,
        DynValueType::Bool => 4,
        DynValueType::U16 | DynValueType::I16 => 2,
        DynValueType::U32 | DynValueType::I32 | DynValueType::F32 => 4,
        DynValueType::U64
        | DynValueType::I64
        | DynValueType::F64
        | DynValueType::Usize
        | DynValueType::Isize => 8,
        DynValueType::Str(_) => 1,
        DynValueType::PodStruct { size } => {
            let s = *size as usize;
            if s == 0 {
                1
            } else {
                s.min(8).next_power_of_two()
            }
        }
        DynValueType::Struct(_)
        | DynValueType::Array(_)
        | DynValueType::Option(_)
        | DynValueType::ByRef(_)
        | DynValueType::HashMap(_)
        | DynValueType::Enum(_) => 8,
        DynValueType::Lazy(resolve) => dyn_value_align(resolve()),
    }
}

pub fn dyn_value_size(vt: &DynValueType) -> usize {
    match vt {
        DynValueType::U8 | DynValueType::I8 => 1,
        DynValueType::Bool => 4,
        DynValueType::U16 | DynValueType::I16 => 2,
        DynValueType::U32 | DynValueType::I32 | DynValueType::F32 => 4,
        DynValueType::U64
        | DynValueType::I64
        | DynValueType::F64
        | DynValueType::Usize
        | DynValueType::Isize => 8,
        DynValueType::PodStruct { size } => *size as usize,
        _ => 0, // non-pod: variable size
    }
}

#[inline(always)]
pub(crate) const fn align_up(offset: usize, align: usize) -> usize {
    (offset + align - 1) & !(align - 1)
}

fn is_byref_value_type(vt: &DynValueType) -> bool {
    matches!(vt, DynValueType::ByRef(_) | DynValueType::Option(DynValueType::ByRef(_)))
}

impl DynValueType {
    pub fn is_numeric(&self) -> bool {
        matches!(
            self,
            DynValueType::U32
                | DynValueType::U64
                | DynValueType::I32
                | DynValueType::I64
                | DynValueType::F32
                | DynValueType::F64
                | DynValueType::U16
                | DynValueType::I16
                | DynValueType::U8
                | DynValueType::I8
                | DynValueType::Usize
                | DynValueType::Isize
        )
    }

    pub fn is_string(&self) -> bool {
        matches!(self, DynValueType::Str(_))
    }

    pub fn is_struct(&self) -> bool {
        matches!(self, DynValueType::Struct(_))
    }

    pub fn is_array(&self) -> bool {
        matches!(self, DynValueType::Array(_))
    }
}

// ---------------------------------------------------------------------------
// GetSchema trait
// ---------------------------------------------------------------------------

/// Trait for types that have a static `StructSchema`.
///
/// Generated by `#[derive(MmapStruct)]` behind `feature = "dyn"`.
pub trait GetSchema {
    fn get_struct_schema() -> &'static StructSchema;

    /// The `DynValueType` that represents the root of this struct.
    fn root_value_type() -> &'static DynValueType;

    /// Create a root `Value` for this struct at offset 0 with the given total size.
    fn root_value(total_size: u64) -> Value {
        Value::new(0, total_size, Self::root_value_type())
    }
}

// ---------------------------------------------------------------------------
// Pod schema resolution (autoref specialization)
// ---------------------------------------------------------------------------

/// Zero-sized marker used to detect `GetSchema` availability at
/// monomorphization time via autoref specialization (stable Rust).
///
/// Must be probed from a **concrete** (e.g. proc-macro generated) context —
/// inside a generic function, method resolution happens once generically and
/// always prefers the unconditional fallback.
pub struct PodResolve<T>(pub core::marker::PhantomData<T>);

/// Higher-priority candidate (`Self = PodResolve<T>`, matched at the autoref
/// step): picked whenever `T: GetSchema`.
pub trait PodViaGetSchema {
    fn resolve_pod(&self) -> Option<&'static DynValueType>;
}
impl<T: GetSchema> PodViaGetSchema for PodResolve<T> {
    fn resolve_pod(&self) -> Option<&'static DynValueType> {
        Some(T::root_value_type())
    }
}

/// Lower-priority fallback (`Self = &mut PodResolve<T>`, matched only at the
/// autoref-mut step): used when `T` does not implement [`GetSchema`].
pub trait PodViaOpaque {
    fn resolve_pod(self) -> Option<&'static DynValueType>;
}
impl<T> PodViaOpaque for &mut PodResolve<T> {
    fn resolve_pod(self) -> Option<&'static DynValueType> {
        None
    }
}
