/// Trait for types that have a static `StructSchema`.
///
/// Generated by `#[derive(MmapStruct)]` behind `feature = "dyn"`.
pub trait GetSchema {
    fn get_schema() -> &'static StructSchema;

    /// The `DynValueType` that represents the root of this struct.
    fn root_value_type() -> &'static DynValueType;

    /// Create a root `Value` for this struct at offset 0 with the given total size.
    fn root_value(total_size: u64) -> Value {
        Value::new(0, total_size, Self::root_value_type())
    }
}
